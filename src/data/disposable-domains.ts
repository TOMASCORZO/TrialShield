export function isDisposableWildcard(domain: string): boolean {
  const lower = domain.toLowerCase();
  return DISPOSABLE_WILDCARDS.some(w => lower.includes(w));
}

// ─── Comprehensive check ─────────────────────────────────────────
export function isDefinitelyDisposable(domain: string): boolean {
  return isDisposableEmail(domain) || isDisposableWildcard(domain);
}

export function isDisposableEmail(domain: string): boolean {
  return DISPOSABLE_DOMAINS.has(domain.toLowerCase());
}

export function isFreeEmailProvider(domain: string): boolean {
  return FREE_EMAIL_PROVIDERS.has(domain.toLowerCase());
}

export function isSuspiciousTLD(domain: string): boolean {
  const tld = '.' + domain.split('.').pop()?.toLowerCase();
  return SUSPICIOUS_TLDS.has(tld);
}

